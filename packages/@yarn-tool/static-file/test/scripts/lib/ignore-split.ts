/**
 * 忽略規則分割片段的主題定義與共用輔助（分割與組合腳本的單一事實來源）
 * Topic definitions and shared helpers of the split ignore-rule fragments
 * (the single source of truth for the split and compose scripts)
 *
 * 片段檔案位於 test/fixtures/split/{git,npm,shared,other}/NN-topic.txt，
 * 依「第一層 git 專用 / npm 發布專用 / 兩類共用 / 其他、第二層主題分類」保存。
 *
 * Fragments live in test/fixtures/split/{git,npm,shared,other}/NN-topic.txt,
 * sorted by the first-level buckets (git-only / npm-only / shared / other)
 * and the second-level topics below.
 *
 * 重複的語法矩陣（測試建置產物、*.map、spec 副檔名…）不逐行手寫：
 * 片段中只放 `# %gen:NAME%` 佔位行，組合時由本檔的產生器展開，
 * 以單一事實來源避免多份手抄副本漂移。
 *
 * Repetitive matrices (test build artifacts, *.map, spec filenames…) are never
 * hand-copied: fragments only carry a `# %gen:NAME%` placeholder line, which the
 * generators below expand at composition time — a single source of truth instead
 * of drifting manual copies.
 *
 * 本檔是「分割（split-ignore-files.ts）」與「組合（compose-split-ignore-files.ts）」
 * 兩支腳本的共用事實來源：主題、分類 ↔ 檔名、片段路徑慣例與輔助區塊定義都只存在於此。
 * This file is the shared source of truth for both scripts (split-ignore-files.ts
 * and compose-split-ignore-files.ts): topics, the bucket ↔ file name mapping, the
 * fragment path convention, and the generator blocks are all defined here only.
 */
import { existsSync, readFileSync } from 'fs';
import { join } from 'path';
import { __ROOT } from '../../__root';

export enum EnumIgnoreSplitTargetBucket
{
	git = 'git',
	npm = 'npm',
	shared = 'shared',
	other = 'other',
}

/**
 * 二層分類主題，陣列順序即全域組合順序
 * Second-level topics; the array order is the global assembly order
 *
 * 編號前綴刻意留出間隙（05、10、20…），方便日後插入新主題而不需重排。
 * The numeric prefixes leave gaps (05, 10, 20…) so new topics can be inserted
 * without renumbering the rest.
 */
export const TOPICS = [
	{ id: '00-header', zh: '檔案頭', en: 'file header' },
	{ id: '01-hidden', zh: '根目錄隱藏檔', en: 'root hidden files' },
	{ id: '05-source', zh: 'npm 來源檔規則', en: 'npm source rules' },
	{ id: '10-project', zh: '專案檔', en: 'project files' },
	{ id: '20-test', zh: '測試檔', en: 'test files' },
	{ id: '30-ide', zh: 'IDE 與編輯器設定', en: 'IDE & editor settings' },
	{ id: '40-env', zh: '環境設定', en: 'environment settings' },
	{ id: '90-misc', zh: '未分類', en: 'unclassified' },
	{ id: '99-whitelist', zh: '白名單例外', en: 'whitelist exceptions' },
] as const;

/**
 * 主題 id 的聯合型別，由 {@link TOPICS} 派生
 * Union of topic ids, derived from {@link TOPICS}
 */
export type IIgnoreSplitTopicId = typeof TOPICS[number]['id'];

/**
 * 會輸出到組合結果的分類（other 永不輸出）
 * Buckets emitted into the composed output (other is never emitted)
 */
export const EMITTED_BUCKETS = [EnumIgnoreSplitTargetBucket.git, EnumIgnoreSplitTargetBucket.npm, EnumIgnoreSplitTargetBucket.shared] as const;

/**
 * 輸出分類的聯合型別，由 {@link EMITTED_BUCKETS} 派生
 * Union of emitted buckets, derived from {@link EMITTED_BUCKETS}
 */
export type IIgnoreSplitEmittedBucket = typeof EMITTED_BUCKETS[number];

/**
 * 組合目標：分類與對應的 ignore 檔名，為「分類 ↔ 檔名」的單一事實來源
 * Composition targets: the bucket and its ignore file name — the single source
 * of truth for the bucket ↔ file-name mapping
 */
export const IGNORE_SPLIT_TARGETS = [
	{ bucket: EnumIgnoreSplitTargetBucket.git, fileName: 'gitignore' },
	{ bucket: EnumIgnoreSplitTargetBucket.npm, fileName: 'npmignore' },
] as const;

/**
 * 可作為組合目標的分類，由 {@link IGNORE_SPLIT_TARGETS} 派生
 * Buckets usable as composition targets, derived from {@link IGNORE_SPLIT_TARGETS}
 */
export type IIgnoreSplitTargetBucket = typeof IGNORE_SPLIT_TARGETS[number]['bucket'];

/**
 * 分類片段的根目錄 / Root directory of the classified fragments
 */
export const SPLIT_ROOT = join(__ROOT, 'test', 'fixtures', 'split');

/**
 * 取得片段檔案路徑，命名慣例為 `<分類>/<主題>.txt`
 * Get a fragment file path, following the `<bucket>/<topic>.txt` naming convention
 *
 * 分割腳本與組合腳本共用此函式，避免各自拼出不同的存放位置。
 * Shared by the split and compose scripts so neither builds its own location.
 *
 * @param bucket - 分類 / Bucket
 * @param topic - 主題編號 / Topic id
 * @returns 片段檔案的絕對路徑 / The absolute path of the fragment file
 */
export function getSplitFragmentPath(bucket: EnumIgnoreSplitTargetBucket, topic: IIgnoreSplitTopicId): string
{
	return join(SPLIT_ROOT, bucket, `${topic}.txt`);
}

/**
 * 片段中的佔位行：`# %gen:<名稱>%`
 * Placeholder line inside a fragment: `# %gen:<name>%`
 */
const GEN_PLACEHOLDER_RE = /^# %gen:([a-z0-9-]+)%$/;

/**
 * git：測試建置產物矩陣
 * git: test build artifact matrix
 *
 * 覆蓋 temp 產物、source map，以及 js/d.ts、mjs/d.mts、cjs/d.cts 三個族系
 * 在 test、tests、packages/* 等目錄下的組合。
 *
 * Covers temp artifacts, source maps, and the js/d.ts, mjs/d.mts, cjs/d.cts
 * families across the test, tests, and packages/* directories.
 *
 * @returns 片段內容行（含分類說明註解與組內空行）/ Fragment lines (including its description comment and intra-group blanks)
 */
export function genTestBuildArtifacts(): string[]
{
	const lines: string[] = [
		'# 測試建置產物（共用輔助產生）/ test build artifacts (generated by shared helper)',
	];

	for (const dir of ['test', 'tests'])
	{
		lines.push(`${dir}/temp*`, `${dir}/**/*.map`);
	}

	lines.push('/packages/*/test/temp*', '/packages/*/tests/temp*', '');

	/**
	 * 每個族系：實作副檔名與其聲明檔配對，重複的目錄組合交給迴圈展開
	 * Per family: the implementation extension paired with its declaration file,
	 * with the repeated directory combinations expanded by the loop
	 */
	const families: [string, string][] = [
		['js', 'd.ts'],
		['mjs', 'd.mts'],
		['cjs', 'd.cts'],
	];

	families.forEach(([ext, decl], index) =>
	{
		if (index)
		{
			lines.push('');
		}

		for (const dir of ['test', 'tests'])
		{
			lines.push(`${dir}/**/*.${ext}`, `${dir}/**/*.${decl}`, `${dir}/*.${ext}`, `${dir}/*.${decl}`);
		}

		lines.push(`bin/*.${decl}`, `bin/**/*.${decl}`, `/packages/*/bin/*.${decl}`);

		for (const dir of ['/packages/*/test', '/packages/*/tests'])
		{
			lines.push(`${dir}/**/*.${ext}`, `${dir}/**/*.${decl}`, `${dir}/*.${ext}`, `${dir}/*.${decl}`);
		}
	});

	return lines;
}

/**
 * git：*.map 對應檔規則
 * git: *.map source file rules
 *
 * 六種模組副檔名的對應檔，一行一個族系無法由其他規則取代，故集中產生。
 * The mapping files of six module extensions; centralized here since no single
 * rule can cover them.
 *
 * @returns 片段內容行 / Fragment lines
 */
export function genSourceMaps(): string[]
{
	return [
		'# *.map 對應檔（共用輔助產生）/ *.map files (generated by shared helper)',
		'*.js.map',
		'*.cjs.map',
		'*.mjs.map',
		'*.ts.map',
		'*.cts.map',
		'*.mts.map',
	];
}

/**
 * npm：spec / test 副檔名矩陣
 * npm: spec & test filename matrix
 *
 * 四種前綴（spec、test、node-spec、node-test）× 四組副檔名族系
 * （d.ts+js/ts、d.cts+cjs/cts、d.mts+mjs/mts、d.tsx+tsx）的笛卡兒積。
 *
 * The cartesian product of four prefixes (spec, test, node-spec, node-test)
 * and four extension families (d.ts+js/ts, d.cts+cjs/cts, d.mts+mjs/mts,
 * d.tsx+tsx).
 *
 * @returns 片段內容行 / Fragment lines
 */
export function genSpecFiles(): string[]
{
	const lines: string[] = [
		'# spec / test 副檔名矩陣（共用輔助產生）/ spec & test filename matrix (generated by shared helper)',
	];

	const prefixes = ['spec', 'test', 'node-spec', 'node-test'];

	const families = [
		{ decl: 'd.ts', impls: ['js', 'ts'] },
		{ decl: 'd.cts', impls: ['cjs', 'cts'] },
		{ decl: 'd.mts', impls: ['mjs', 'mts'] },
		{ decl: 'd.tsx', impls: ['tsx'] },
	];

	prefixes.forEach((prefix, prefixIndex) =>
	{
		if (prefixIndex)
		{
			lines.push('');
		}

		families.forEach((family, familyIndex) =>
		{
			if (familyIndex)
			{
				lines.push('');
			}

			lines.push(`*.${prefix}.${family.decl}`);

			for (const impl of family.impls)
			{
				lines.push(`*.${prefix}.${impl}`);
			}
		});
	});

	return lines;
}

/**
 * npm：來源與聲明檔規則群
 * npm: source & declaration rule groups
 *
 * 三種聲明副檔名（d.ts、d.mts、d.cts）各自的白名單與 /bin 目錄規則，
 * 必須維持在相鄰行才能與前後的排除規則正確互動。
 *
 * The whitelist and /bin rules for the three declaration extensions
 * (d.ts, d.mts, d.cts); they must stay on adjacent lines to interact correctly
 * with the surrounding exclusion rules.
 *
 * @returns 片段內容行 / Fragment lines
 */
export function genNpmSourceDeclarations(): string[]
{
	const lines: string[] = [
		'# npm 來源與聲明檔規則（共用輔助產生）/ npm source & declaration rules (generated by shared helper)',
	];

	['d.ts', 'd.mts', 'd.cts'].forEach((decl, index) =>
	{
		if (index)
		{
			lines.push('');
		}

		lines.push(`!*.${decl}`, `/bin/**/*.${decl}`, `/bin/*.${decl}`);
	});

	return lines;
}

/**
 * 共用輔助區塊的註冊資料：產生函式、所屬主題與所屬分類都登记在此，
 * 分割腳本據此決定佔位行寫入哪個片段，組合腳本據此展開佔位內容
 * Registration of a shared generator: the generate function, its topic, and its
 * bucket all live here, so the split script knows which fragment receives the
 * placeholder line and the compose script knows what to expand it into
 */
export interface IIgnoreSplitGenerator
{
	/**
	 * 產生區塊內容（含說明註解與組內空行）
	 * Produce the block content (including its description comment and intra-group blanks)
	 */
	generate: () => string[];

	/**
	 * 區塊所屬主題 / The topic this block belongs to
	 */
	topic: IIgnoreSplitTopicId;

	/**
	 * 區塊所屬分類；只有目標分類（git / npm）會以輔助產生
	 * Bucket of the block; only target buckets (git / npm) are produced by helpers
	 */
	bucket: IIgnoreSplitTargetBucket;
}

/**
 * 產生器註冊表：鍵名對應片段中的 `# %gen:NAME%` 佔位名稱
 * Generator registry: keys match the `# %gen:NAME%` placeholder names in fragments
 */
export const IGNORE_SPLIT_GENERATORS: Record<string, IIgnoreSplitGenerator> = {
	'test-build-artifacts': { generate: genTestBuildArtifacts, topic: '20-test', bucket: EnumIgnoreSplitTargetBucket.git },
	'source-maps': { generate: genSourceMaps, topic: '10-project', bucket: EnumIgnoreSplitTargetBucket.git },
	'spec-files': { generate: genSpecFiles, topic: '20-test', bucket: EnumIgnoreSplitTargetBucket.npm },
	'npm-source-declarations': { generate: genNpmSourceDeclarations, topic: '05-source', bucket: EnumIgnoreSplitTargetBucket.npm },
};

/**
 * 讀取單一分類片段的所有行
 * Read every line of a single classified fragment
 *
 * 片段首行是分類標頭（主題 × 分類），組合時保留為輸出檔的區段標記；
 * 檔案不存在（該分類 × 主題沒有片段）時回傳空陣列。
 * The first line is the classification header (topic × bucket), kept as the
 * section marker of the composed output; a missing file (no fragment for that
 * bucket × topic combination) yields an empty array.
 *
 * @param bucket - 分類：git、npm 或 shared / Bucket: git, npm, or shared
 * @param topic - 主題編號（{@link TOPICS} 的 id）/ Topic id (see {@link TOPICS})
 * @returns 片段行陣列（已去除結尾空行）/ Fragment lines (trailing blanks removed)
 */
export function readSplitFragment(bucket: EnumIgnoreSplitTargetBucket, topic: IIgnoreSplitTopicId): string[]
{
	const path = getSplitFragmentPath(bucket, topic);

	if (!existsSync(path))
	{
		return [];
	}

	const lines = readFileSync(path, 'utf8').split(/\r?\n/);

	while (lines.length > 0 && lines[lines.length - 1] === '')
	{
		lines.pop();
	}

	return lines;
}

/**
 * 將 `# %gen:NAME%` 佔位行展開為對應產生器的輸出
 * Expand `# %gen:NAME%` placeholder lines into the matching generator output
 *
 * 其餘行原樣保留；遇到未註冊的佔位名稱時拋錯，避免靜默產出不完整的檔案。
 * All other lines pass through unchanged; an unregistered placeholder name
 * throws instead of silently producing an incomplete file.
 *
 * @param lines - 組合後的行陣列 / The assembled line array
 * @returns 展開後的行陣列 / The expanded line array
 */
export function expandGenPlaceholders(lines: readonly string[]): string[]
{
	return lines.flatMap((line) =>
	{
		const matched = GEN_PLACEHOLDER_RE.exec(line);

		if (!matched)
		{
			return [line];
		}

		const generator = IGNORE_SPLIT_GENERATORS[matched[1]];

		if (!generator)
		{
			throw new Error(`unknown ignore split generator placeholder: ${line}`);
		}

		return generator.generate();
	});
}
